package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/primandproper/platform-go/v14/authorization/database/internal/queries"
	"github.com/primandproper/platform-go/v14/authorization/database/migrations"

	"github.com/primandproper/primitives-go/database/dialect"
)

// header marks the output as generated in the form `go generate` consumers,
// linters, and review tools all recognize. SQL's line comment is the same on
// all three dialects, and sqlc reads its own annotations out of comments, so
// this has to be a comment sqlc will ignore rather than one it might parse.
const header = "-- Code generated by github.com/primandproper/platform-go/v14/authorization/database/internal/queriesgen. DO NOT EDIT.\n\n"

// dialects is the roster this package serves, which is the same list
// unison.yaml's schemas map is keyed on.
func dialects() []dialect.Dialect {
	return []dialect.Dialect{dialect.Postgres, dialect.MySQL, dialect.SQLite}
}

func main() {
	schema := flag.String("schema", "", "print the authorization DDL for this dialect instead of writing the queries")
	out := flag.String("out", filepath.Join("internal", "queries"), "directory the generated .sql files are written to")

	flag.Parse()

	if err := run(*schema, *out); err != nil {
		fmt.Fprintln(os.Stderr, "queriesgen:", err)
		os.Exit(1)
	}
}

// run does one of the two jobs, so that neither has to call os.Exit itself.
func run(schema, out string) error {
	if schema != "" {
		return printSchema(dialect.Dialect(schema))
	}

	for _, d := range dialects() {
		path := filepath.Join(out, queries.FileName(d))
		if err := os.WriteFile(path, []byte(header+queries.Render(d)), 0o600); err != nil {
			return fmt.Errorf("writing %q: %w", path, err)
		}
	}

	return nil
}

// printSchema writes the DDL for one dialect to stdout, at the empty prefix —
// which is the name the canonical queries use, and the only prefix sqlc could
// resolve, since an identifier is not a bind parameter in any of the three
// engines.
func printSchema(d dialect.Dialect) error {
	ddl, err := migrations.SQL(d, "")
	if err != nil {
		return fmt.Errorf("rendering the %s schema: %w", d, err)
	}

	_, err = fmt.Fprintln(os.Stdout, ddl)

	return err
}
